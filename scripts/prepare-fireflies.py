"""Prepare a static forest and a compact 18-light sprite from the original SVG.
Run from the project root: python scripts/prepare-fireflies.py
The original background.svg is never modified.
"""
from pathlib import Path
from copy import deepcopy
import xml.etree.ElementTree as ET
import re
import json
import gzip

ET.register_namespace("", "http://www.w3.org/2000/svg")
NS = "{http://www.w3.org/2000/svg}"
folder = Path("src/assets/images")
root = ET.parse(folder / "background.svg").getroot()
main, defs = root[0], root[1]
children = list(main)
by_id = {node.get("id"): node for node in defs}
selected = [4466, 4474, 4478, 4486, 4490, 4494, 4498, 4502, 4506,
            4514, 4518, 4530, 4548, 4562, 4566, 4578, 4582, 4596]
sprite = ET.Element(NS + "svg", {"width": "768", "height": "384", "viewBox": "0 0 768 384"})
sprite_defs = ET.SubElement(sprite, NS + "defs")
lights = []
removed = set()
for number, index in enumerate(selected):
    nodes = children[index:index + 4]
    assert nodes[0].get("opacity") == "0.45"
    filter_id = re.search(r"url\(#(.*?)\)", nodes[0].get("filter"))[1]
    glow_filter = by_id[filter_id]
    cx = float(glow_filter.get("x")) + float(glow_filter.get("width")) / 2
    cy = float(glow_filter.get("y")) + float(glow_filter.get("height")) / 2
    col, row = number % 6, number // 6
    group = ET.SubElement(sprite, NS + "g", {"transform": f"translate({col * 128 + 64 - cx:g} {row * 128 + 64 - cy:g})"})
    for node in nodes:
        group.append(deepcopy(node))
        removed.add(node)
        for ref in re.findall(r"url\(#(.*?)\)", ET.tostring(node, encoding="unicode")):
            sprite_defs.append(deepcopy(by_id[ref]))
    # Water reflections belong to their light too.
    for node in children[index + 4:index + 6]:
        if node.get("fill") == "black" or node.get("stroke-opacity") == "0.25":
            removed.add(node)
    lights.append({"id": number, "x": round(cx, 2), "y": round(cy, 2),
                   "column": col, "row": row,
                   "duration": round(6.2 + (number * 17 % 39) / 10, 1),
                   "delay": round(-(number * 1.73 % 10), 2)})
for node in removed:
    main.remove(node)
# Remove unused filter definitions from the static background.
used = set(re.findall(r"url\(#(.*?)\)", ET.tostring(main, encoding="unicode")))
pending = list(used)
while pending:
    identifier = pending.pop()
    if identifier not in by_id:
        continue
    for ref in re.findall(r"url\(#(.*?)\)", ET.tostring(by_id[identifier], encoding="unicode")):
        if ref not in used:
            used.add(ref)
            pending.append(ref)
for node in list(defs):
    if node.get("id") not in used:
        defs.remove(node)
for filename, element in [("background-forest.svg", root), ("fireflies-sprite.svg", sprite)]:
    content = ET.tostring(element, encoding="utf-8")
    (folder / filename).write_bytes(content)
    print(f"{filename}: {len(content)} bytes; gzip {len(gzip.compress(content))} bytes")
Path("src/components/Preview/fireflies.data.ts").write_text(
    "// Generated by scripts/prepare-fireflies.py from the original background.\n"
    + "export const fireflies = " + json.dumps(lights, indent=2) + ";\n", encoding="utf-8")
print(f"Extracted {len(lights)} lights; preserved the original SVG.")
